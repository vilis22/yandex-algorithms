class Sorting:
    def __init__(self, dct):
        self.dct = dct

    def sort_lst(self) -> list[str]:
        priorities = {
            "металл": {"золото": 10, "серебро": 8, "медь": 5, "алюминий": 3, "железо": 1},
            "пластик": {"ПЭ": 10, "ПС": 8, "ПП": 6, "ПВХ": 5, "ПЭТ": 2},
            "остальное": {"промышленные": 7, "пищевые": 4, "биологические": 1},
        }
        cat_order = {"металл": 3, "пластик": 2, "остальное": 1}

        def score(pair):
            key, val = pair
            cat, sub = (s.strip() for s in val.split("-"))
            return cat_order[cat], priorities[cat][sub]

        return [key for key, _ in sorted(self.dct.items(), key=score, reverse=True)]

    def __getattr__(self, item):
        return "Атрибут не существует"


